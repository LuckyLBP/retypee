#!/usr/bin/env python3
"""Builds web/icons.svg (one <symbol> per page, id "i-<page id>") from the Lucide icons named in
scripts/site/registry.py. Run it after changing ICON_OF or LUCIDE; the sprite is committed.

    python3 scripts/fetch_icons.py
"""
import os
import re
import sys
import urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
sys.path.insert(0, os.path.join(ROOT, "scripts", "site"))
import registry as R  # noqa: E402


def fetch(name):
    url = f"https://cdn.jsdelivr.net/npm/lucide-static@{R.LUCIDE}/icons/{name}.svg"
    with urllib.request.urlopen(url, timeout=30) as r:
        return r.read().decode("utf-8")


def main():
    missing = [p for p in R.PAGES if p not in R.ICON_OF]
    if missing:
        sys.exit(f"no icon chosen for: {', '.join(missing)}")
    cache = {}
    symbols = []
    for pid in R.PAGES:
        name = R.ICON_OF[pid]
        svg = cache.get(name) or cache.setdefault(name, fetch(name))
        m = re.search(r"<svg[^>]*>(.*)</svg>", svg, re.S)
        if not m or "<" not in m.group(1):
            sys.exit(f"unexpected SVG for {name}")
        inner = re.sub(r"\s+", " ", m.group(1)).strip()
        symbols.append(f'<symbol id="i-{pid}" viewBox="0 0 24 24">{inner}</symbol>')
    out = ('<svg xmlns="http://www.w3.org/2000/svg">\n<!-- Lucide icons v' + R.LUCIDE + ' (ISC licence, https://lucide.dev). Generated by scripts/fetch_icons.py -->\n'
           + "\n".join(symbols) + "\n</svg>\n")
    path = os.path.join(ROOT, "web", "icons.svg")
    with open(path, "w", encoding="utf-8") as f:
        f.write(out)
    print(f"wrote {path}: {len(symbols)} icons, {len(out) / 1024:.1f} KB, {len(cache)} distinct Lucide icons")


if __name__ == "__main__":
    main()
